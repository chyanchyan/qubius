import { EdgeError, type EdgeRegistry, type EdgeSecrets, type RegistrySite } from "./types.js";

/**
 * Caddyfile 渲染：与 edgectl 0.1.0 的 render.py 逐字节一致。
 *
 * 这里只做纯字符串渲染，不执行任何命令、不读写文件。写入 VPS / 本地网关
 * 由上层决定；本单元只保证字节 parity，方便用 edgectl render 的 golden 对比。
 */

export const MANAGED_START = "# >>> edgectl managed block - do not edit (generated) >>>";
export const MANAGED_END = "# <<< edgectl managed block - do not edit (generated) <<<";

const SITE_ADDR_RE = /^(?:[a-z][a-z0-9+.-]*:\/\/)?([^:/\s]+)(?::\d+)?$/;

function proxyLines(registry: EdgeRegistry, site: RegistrySite, indent: string): string[] {
  const upstream = `${registry.vps.tunnelBind}:${registry.vps.gatewayPort}`;
  const lines = [`${indent}reverse_proxy ${upstream} {`];
  if (site.sse) lines.push(`${indent}\tflush_interval -1`);
  lines.push(`${indent}}`);
  return lines;
}

function requireDevAuth(registry: EdgeRegistry, secrets: EdgeSecrets | undefined): {
  username: string;
  passwordHash: string;
  cookieSecret: string;
  cookieName: string;
} {
  const auth = registry.authDev;
  if (!secrets?.passwordHash || !secrets.cookieSecret) {
    throw new EdgeError(
      `缺少 dev 认证密钥；先设置 ${auth.passwordHashEnv} 和 ${auth.cookieSecretEnv}。`,
    );
  }
  return {
    username: auth.username,
    passwordHash: secrets.passwordHash,
    cookieSecret: secrets.cookieSecret,
    cookieName: auth.cookieName,
  };
}

/** 渲染追加到 VPS Caddyfile 的托管块；没有站点时返回空串。 */
export function renderVpsBlock(registry: EdgeRegistry, secrets?: EdgeSecrets): string {
  if (registry.sites.length === 0) return "";
  const hasDev = registry.sites.some((site) => site.auth === "dev");
  const dev = hasDev ? requireDevAuth(registry, secrets) : undefined;
  const lines: string[] = [MANAGED_START];
  for (const site of registry.sites) {
    const addresses = site.domains.join(", ");
    lines.push(`${addresses} {`);
    lines.push("\tencode zstd gzip");
    if (site.auth === "dev") {
      const auth = dev!;
      const cookie = `${auth.cookieName}=${auth.cookieSecret}`;
      lines.push("");
      lines.push(`\t@auth header Cookie *${cookie}*`);
      lines.push("\thandle @auth {");
      lines.push(...proxyLines(registry, site, "\t\t"));
      lines.push("\t}");
      lines.push("");
      lines.push("\troute {");
      lines.push("\t\tbasic_auth {");
      lines.push(`\t\t\t${auth.username} ${auth.passwordHash}`);
      lines.push("\t\t}");
      lines.push(
        `\t\theader +Set-Cookie "${cookie}; Path=/; Secure; HttpOnly; SameSite=Strict; Max-Age=604800"`,
      );
      lines.push(...proxyLines(registry, site, "\t\t"));
      lines.push("\t}");
    } else {
      lines.push(...proxyLines(registry, site, "\t"));
    }
    lines.push("}");
    lines.push("");
  }
  lines.push(MANAGED_END);
  return `${lines.join("\n").replace(/\s+$/, "")}\n`;
}

/** 渲染本地网关 Caddyfile（只监听 127.0.0.1，按 Host 路由）。 */
export function renderLocalCaddyfile(registry: EdgeRegistry): string {
  const listen = `:${registry.vps.gatewayPort}`;
  const lines: string[] = [
    "{",
    "\tadmin localhost:2019",
    "\tauto_https off",
    "}",
    "",
    `http://${listen} {`,
    "\tbind 127.0.0.1",
  ];
  for (const [index, site] of registry.sites.entries()) {
    const matcher = `@site_${index}`;
    const domains = site.domains.join(" ");
    lines.push(`\t${matcher} host ${domains}`);
    lines.push(`\thandle ${matcher} {`);
    lines.push(`\t\treverse_proxy ${site.upstream} {`);
    lines.push("\t\t\theader_up Host {host}");
    lines.push("\t\t\theader_up X-Forwarded-Proto {http.request.header.X-Forwarded-Proto}");
    lines.push("\t\t\theader_up X-Forwarded-Host {http.request.header.X-Forwarded-Host}");
    if (site.sse) lines.push("\t\t\tflush_interval -1");
    lines.push("\t\t}");
    lines.push("\t}");
    lines.push("");
  }
  lines.push("\thandle {");
  lines.push('\t\trespond "edgectl: no site for this host" 404');
  lines.push("\t}");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

/** 完整的 VPS 托管 Caddyfile（含 edgectl 头注释），与 render_all 一致。 */
export function renderVpsCaddyfile(registry: EdgeRegistry, secrets?: EdgeSecrets): string {
  const block = renderVpsBlock(registry, secrets);
  if (!block) return "# No sites configured.\n";
  return (
    "# Generated by edgectl. Apply with: edgectl apply-vps\n" +
    "# This file contains secrets; keep it out of version control.\n\n" +
    block
  );
}

/** 替换或追加托管块，保留 marker 之外的原文；CRLF 归一化为 LF。 */
export function spliceManaged(existing: string, block: string): string {
  const text = existing.replace(/\r\n/g, "\n");
  const start = text.indexOf(MANAGED_START);
  const end = text.indexOf(MANAGED_END);
  const hasStart = start !== -1;
  const hasEnd = end !== -1;
  if (hasStart !== hasEnd || (hasStart && end < start)) {
    throw new EdgeError(
      "远端 Caddyfile 里的 edgectl 标记不完整；请先手动修复 " +
        `(${MANAGED_START} / ${MANAGED_END})。`,
    );
  }
  const normalized = block.replace(/^\n+|\n+$/g, "");
  if (!hasStart) {
    if (!normalized) return existing;
    let base = text.replace(/\n+$/, "");
    if (base) base += "\n\n";
    return `${base}${normalized}\n`;
  }
  const before = text.slice(0, start).replace(/\n+$/, "");
  const after = text.slice(end + MANAGED_END.length).replace(/^\n+/, "");
  const parts = [before, normalized, after].filter((part) => part.length > 0);
  if (parts.length === 0) return "";
  return `${parts.join("\n\n")}\n`;
}

function stripManaged(text: string): string {
  const start = text.indexOf(MANAGED_START);
  const end = text.indexOf(MANAGED_END);
  if (start === -1 || end === -1 || end < start) return text;
  return text.slice(0, start) + text.slice(end + MANAGED_END.length);
}

function siteAddressTokens(head: string): string[] {
  const tokens = head.trim().split(/[,\s]+/);
  const result: string[] = [];
  for (const raw of tokens) {
    const token = raw.trim().replace(/^"+|"+$/g, "");
    if (!token || token.startsWith("{$") || token.startsWith("(")) continue;
    const match = SITE_ADDR_RE.exec(token);
    if (match) result.push(match[1]!.toLowerCase().replace(/\.+$/, ""));
  }
  return result;
}

/** 找出托管块之外、与给定域名冲突的顶层站点块；返回 [行号, 行内容]。 */
export function findConflictingSiteBlocks(
  existing: string,
  domains: Set<string>,
): Array<[number, string]> {
  const text = stripManaged(existing);
  const hits: Array<[number, string]> = [];
  const lines = text.split(/\r?\n/);
  for (const [index, line] of lines.entries()) {
    const lineno = index + 1;
    if (!line.trim() || line.trimStart().startsWith("#")) continue;
    if (line !== line.trimStart()) continue; // 站点地址行必须顶格。
    if (!line.trimEnd().endsWith("{")) continue;
    const head = line.trimEnd().slice(0, -1).trim();
    if (!head) continue;
    if (siteAddressTokens(head).some((token) => domains.has(token))) {
      hits.push([lineno, line.trim()]);
    }
  }
  return hits;
}

/** 把文本里出现的密钥替换为 <redacted>。 */
export function redact(text: string, secrets: string[]): string {
  let out = text;
  for (const secret of secrets) {
    if (secret) out = out.split(secret).join("<redacted>");
  }
  return out;
}

/** 渲染结果里需要脱敏的密钥列表。 */
export function secretValues(secrets: EdgeSecrets | undefined): string[] {
  if (!secrets) return [];
  return [secrets.passwordHash, secrets.cookieSecret].filter((value) => Boolean(value));
}
